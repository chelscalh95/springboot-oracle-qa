-- Schema required by the application (table PERSON in the application user's schema).
-- Source: DDL in the upstream README ("Create the table that your Spring Boot application needs").
-- The application does NOT create this table itself (spring.jpa.hibernate.ddl-auto is not set,
-- which means "none" for a non-embedded database), so it must exist before the app starts.
-- Applied by:  npm run db:init   (idempotent: an existing table is left untouched)
CREATE TABLE Person (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  first_name VARCHAR2(255) NOT NULL,
  last_name VARCHAR2(255) NOT NULL,
  birth_date DATE NOT NULL,
  CONSTRAINT pk_person PRIMARY KEY (id)
);
